"""Stable, counted diagnostic debt anchored to logical modules and Python ASTs.

Line numbers aid navigation only.  They are absent from diagnostic identity.
The baseline is data reviewed in git, never regenerated by the CI check command.
"""

from __future__ import annotations

import ast
import hashlib
import json
import subprocess
from collections import Counter
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

type JsonValue = None | bool | int | float | str | list["JsonValue"] | dict[str, "JsonValue"]


def json_value(value: object) -> JsonValue:
    """Validate an external JSON value before it enters gate data structures."""
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, list):
        return [json_value(item) for item in value]
    if isinstance(value, dict):
        result: dict[str, JsonValue] = {}
        for key, item in value.items():
            if not isinstance(key, str):
                raise ValueError("JSON mapping keys must be strings")
            result[key] = json_value(item)
        return result
    raise ValueError("Unsupported JSON value")


def load_json(path: Path) -> JsonValue:
    value: object = json.loads(path.read_text(encoding="utf-8"))
    return json_value(value)


def mapping(value: JsonValue) -> dict[str, JsonValue]:
    if not isinstance(value, dict):
        raise ValueError("Expected a JSON object")
    return value


def sequence(value: JsonValue) -> list[JsonValue]:
    if not isinstance(value, list):
        raise ValueError("Expected a JSON list")
    return value


def string(value: JsonValue) -> str:
    if not isinstance(value, str):
        raise ValueError("Expected a JSON string")
    return value


def integer(value: JsonValue) -> int:
    if type(value) is not int:
        raise ValueError("Expected a JSON integer")
    return value


def digest(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def module_id(path: str) -> str:
    parts = path.removesuffix(".py").split("/")
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


@dataclass(frozen=True)
class SourceIndex:
    path: str
    source_digest: str
    ast_digest: str
    nodes: tuple[ast.AST, ...]
    symbols: tuple[tuple[int, int, str], ...]

    def unit_digests(self) -> dict[str, str]:
        result: dict[str, list[str]] = {}
        scope_names = {(start, end): name for start, end, name in self.symbols}
        for node in self.nodes:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                name = scope_names[(node.lineno, node.end_lineno or node.lineno)]
                result.setdefault(name, []).append(
                    digest(ast.dump(node, include_attributes=False).encode())
                )
            elif isinstance(node, ast.Module):
                body = [
                    item
                    for item in node.body
                    if not isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
                ]
                result["<module>"] = [
                    digest(
                        ast.dump(
                            ast.Module(body=body, type_ignores=[]), include_attributes=False
                        ).encode()
                    )
                ]
        return {name: digest("\n".join(items).encode()) for name, items in result.items()}

    @classmethod
    def read(cls, root: Path, path: str) -> SourceIndex:
        raw = (root / path).read_bytes()
        return cls.from_source(path, raw)

    @classmethod
    def from_source(cls, path: str, raw: bytes) -> SourceIndex:
        """Index exact source bytes, including immutable committed baseline files."""
        tree = ast.parse(raw, filename=path)
        symbols: list[tuple[int, int, str]] = []

        def visit(node: ast.AST, prefix: str) -> None:
            for child in ast.iter_child_nodes(node):
                name = prefix
                if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    name = f"{prefix}.{child.name}" if prefix else child.name
                    symbols.append((child.lineno, child.end_lineno or child.lineno, name))
                visit(child, name)

        visit(tree, "")
        return cls(
            path,
            digest(raw),
            digest(ast.dump(tree, include_attributes=False).encode()),
            tuple(ast.walk(tree)),
            tuple(symbols),
        )

    def _anchored_node(self, line: int) -> tuple[str, ast.stmt | None]:
        scopes = [(end - start, name) for start, end, name in self.symbols if start <= line <= end]
        symbol = min(scopes)[1] if scopes else "<module>"
        candidates = [
            node
            for node in self.nodes
            if isinstance(node, ast.stmt)
            and node.lineno <= line <= (node.end_lineno or node.lineno)
        ]
        if not candidates:
            return symbol, None
        node = min(candidates, key=lambda item: (item.end_lineno or item.lineno) - item.lineno)
        return symbol, node

    @staticmethod
    def _function_header(
        node: ast.stmt, line: int
    ) -> ast.FunctionDef | ast.AsyncFunctionDef | None:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            return None
        first = node.body[0]
        first_line = first.lineno
        if isinstance(first, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            first_line = min([first_line, *(item.lineno for item in first.decorator_list)])
        if line == node.lineno or node.lineno <= line < first_line:
            return node
        return None

    @staticmethod
    def _signature_digest(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
        payload = ast.dump(node.args, include_attributes=False)
        payload += ast.dump(node.returns, include_attributes=False) if node.returns else "None"
        return digest(payload.encode())

    def function_header_anchors(self, line: int) -> tuple[str, str, str] | None:
        """Return the symbol, canonical and original header anchors for this exact layout."""
        symbol, node = self._anchored_node(line)
        if node is None or self._function_header(node, line) is None:
            return None
        assert isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        canonical = self._signature_digest(node)
        original = (
            canonical
            if line == node.lineno
            else digest(ast.dump(node, include_attributes=False).encode())
        )
        return symbol, canonical, original

    def anchor(self, line: int) -> tuple[str, str]:
        symbol, node = self._anchored_node(line)
        if node is None:
            return symbol, self.ast_digest
        # Every physical header line describes the same signature. Whitespace
        # changes must not turn an argument diagnostic into whole-body debt.
        header = self._function_header(node, line)
        if header is not None:
            return symbol, self._signature_digest(header)
        if isinstance(node, ast.ClassDef) and line == node.lineno:
            payload = repr([ast.dump(base, include_attributes=False) for base in node.bases])
        else:
            payload = ast.dump(node, include_attributes=False)
        return symbol, digest(payload.encode())


@dataclass(frozen=True)
class Diagnostic:
    tool: str
    path: str
    symbol: str
    code: str
    anchor: str
    message: str
    line: int

    @property
    def key(self) -> tuple[str, str, str, str, str, str]:
        return self.tool, module_id(self.path), self.symbol, self.code, self.anchor, self.message

    def record(self) -> dict[str, JsonValue]:
        return {
            "tool": self.tool,
            "symbol": self.symbol,
            "code": self.code,
            "anchor": self.anchor,
            "message": self.message,
            "line": self.line,
        }


def parse_diagnostics(
    root: Path, indices: Mapping[str, SourceIndex], tool: str, text: str
) -> list[Diagnostic]:
    if tool == "mypy":
        rows = [json_value(json.loads(line)) for line in text.splitlines() if line.strip()]
    else:
        rows = sequence(json_value(json.loads(text)))
    diagnostics: list[Diagnostic] = []
    for row in rows:
        data = mapping(row)
        if tool == "mypy" and data.get("severity") != "error":
            continue
        filename = string(data["file"] if tool == "mypy" else data["filename"])
        file_path = Path(filename)
        path = file_path.relative_to(root).as_posix() if file_path.is_absolute() else filename
        if path not in indices:
            raise ValueError(f"Unexpected tool diagnostic outside scan inventory: {path}")
        line = (
            integer(data["line"]) if tool == "mypy" else integer(mapping(data["location"])["row"])
        )
        symbol, anchor = indices[path].anchor(line)
        if tool == "format":
            symbol, anchor = "<module>", indices[path].source_digest
        diagnostics.append(
            Diagnostic(
                tool, path, symbol, string(data["code"]), anchor, string(data["message"]), line
            )
        )
    return diagnostics


def frozen_source_indices(root: Path, data: Mapping[str, JsonValue]) -> dict[str, SourceIndex]:
    """Read the frozen commit, validating every byte digest before anchor interpretation.

    The ledger remains unchanged. Reading current checkout bytes here would
    allow real signature or body edits to reinterpret old diagnostic debt.
    """
    commit = string(data["source_commit"])
    if len(commit) != 40 or any(character not in "0123456789abcdef" for character in commit):
        raise ValueError("Frozen source must identify an exact immutable commit")
    result: dict[str, SourceIndex] = {}
    for raw_module in sequence(data["modules"]):
        module = mapping(raw_module)
        path = string(module["path"])
        if path in result:
            raise ValueError(f"Duplicate frozen source path: {path}")
        completed = subprocess.run(
            ["git", "show", f"{commit}:{path}"], cwd=root, capture_output=True, check=False
        )
        if completed.returncode:
            raise ValueError(f"Frozen source is unavailable: {path}")
        if digest(completed.stdout) != string(module["source_sha256"]):
            raise ValueError(f"Frozen source hash mismatch: {path}")
        result[path] = SourceIndex.from_source(path, completed.stdout)
    return result


def baseline_diagnostics(
    data: Mapping[str, JsonValue], *, source_indices: Mapping[str, SourceIndex] | None = None
) -> list[Diagnostic]:
    result: list[Diagnostic] = []
    for raw_module in sequence(data["modules"]):
        module = mapping(raw_module)
        path = string(module["path"])
        if string(module["module_id"]) != module_id(path):
            raise ValueError(f"Unreviewed logical module mapping: {path}")
        for raw_row in sequence(module["diagnostics"]):
            row = mapping(raw_row)
            anchor = string(row["anchor"])
            symbol = string(row["symbol"])
            line = integer(row["line"])
            if source_indices is not None:
                if path not in source_indices or source_indices[path].path != path:
                    raise ValueError(f"Frozen source index is unavailable: {path}")
                header = source_indices[path].function_header_anchors(line)
                if header is not None and string(row["tool"]) in {"ruff", "mypy"}:
                    old_symbol, canonical, original = header
                    if symbol != old_symbol or anchor not in {canonical, original}:
                        raise ValueError(
                            f"Frozen header diagnostic does not match its source: {path}"
                        )
                    anchor = canonical
            result.append(
                Diagnostic(
                    string(row["tool"]),
                    path,
                    symbol,
                    string(row["code"]),
                    anchor,
                    string(row["message"]),
                    line,
                )
            )
    return result


def added_diagnostics(
    current: Iterable[Diagnostic], baseline: Iterable[Diagnostic]
) -> list[Diagnostic]:
    remaining = Counter(item.key for item in baseline)
    added: list[Diagnostic] = []
    for item in current:
        if remaining[item.key] > 0:
            remaining[item.key] -= 1
        else:
            added.append(item)
    return added


def check_frontier(
    frontier: Mapping[str, JsonValue], paths: Iterable[str], diagnostics: Iterable[Diagnostic]
) -> list[str]:
    actual = set(paths)
    modules = {string(item) for item in sequence(frontier["modules"])}
    failures = [f"Frontier module is missing: {path}" for path in sorted(modules - actual)]
    failures.extend(
        f"Frontier diagnostic: {item.path}:{item.line}: {item.tool}/{item.code}"
        for item in diagnostics
        if item.path in modules
    )
    return failures


def changed_unit_diagnostics(
    baseline: Mapping[str, JsonValue],
    indices: Mapping[str, SourceIndex],
    diagnostics: Iterable[Diagnostic],
) -> list[Diagnostic]:
    old_units = {
        string(module["path"]): mapping(module["unit_digests"])
        for module in (mapping(item) for item in sequence(baseline["modules"]))
    }
    current_units = {path: index.unit_digests() for path, index in indices.items()}
    return [
        item
        for item in diagnostics
        if item.tool != "format"
        and old_units.get(item.path, {}).get(item.symbol)
        != current_units[item.path].get(item.symbol)
    ]
